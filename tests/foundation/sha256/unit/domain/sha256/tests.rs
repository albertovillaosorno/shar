//! Tests unit tests.

use super::{Sha256, digest_hex};

#[test]
fn matches_known_empty_digest() {
    assert_eq!(
        digest_hex(b""),
        "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
    );
}

#[test]
fn matches_known_abc_digest() {
    assert_eq!(
        digest_hex(b"abc"),
        "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
    );
}

#[test]
fn incremental_updates_match_known_abc_digest() {
    let mut digest = Sha256::new();
    digest.update(b"a");
    digest.update(b"b");
    digest.update(b"c");
    assert_eq!(
        digest.finalize_hex(),
        "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
    );
}

#[test]
fn incremental_updates_cross_block_boundaries() {
    let payload = vec![b'a'; 1_000_000];
    let mut digest = Sha256::new();
    for chunk in payload.chunks(8191) {
        digest.update(chunk);
    }
    assert_eq!(
        digest.finalize_hex(),
        "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0"
    );
}

#[test]
fn incremental_padding_boundaries_match_known_digests() {
    for (length, expected) in [
        (
            55,
            "9f4390f8d30c2dd92ec9f095b65e2b9ae9b0a925a5258e241c9f1e910f734318",
        ),
        (
            56,
            "b35439a4ac6f0948b6d6f9e3c6af0f5f590ce20f1bde7090ef7970686ec6738a",
        ),
        (
            63,
            "7d3e74a05d7db15bce4ad9ec0658ea98e3f06eeecf16b4c6fff2da457ddc2f34",
        ),
        (
            64,
            "ffe054fe7ae0cb6dc65c3af9b61d5209f439851db43d0ba5997337df154668eb",
        ),
        (
            65,
            "635361c48bb9eab14198e76ea8ab7f1a41685d6ad62aa9146d301d4f17eb0ae0",
        ),
    ] {
        let payload = vec![b'a'; length];
        let mut digest = Sha256::new();
        for chunk in payload.chunks(7) {
            digest.update(chunk);
        }
        assert_eq!(digest.finalize_hex(), expected, "length={length}");
    }
}
